#!/usr/bin/env python3
"""Generate stubs.S and the p_* slots in proxy_symbols.h for the renderer proxy.

The proxy forwards about 2900 EGL/GL entry points. Each one needs an AArch64
trampoline (stubs.S) and a writable slot that the constructor fills in at load
time (proxy_symbols.h). Writing that by hand is not viable, and the two files
have to agree exactly: a slot without a trampoline is a symbol the linker
cannot resolve, a trampoline without a slot jumps through a null pointer.

Usage, from the repository root:

    python3 tools/gen_proxy.py           # rewrite both files
    python3 tools/gen_proxy.py --check   # exit 1 if they are out of date
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROXY_DIR = ROOT / "android-plugin-ui/app/src/main/cpp/renderer_proxy"
SYMBOLS_H = PROXY_DIR / "proxy_symbols.h"
STUBS_S = PROXY_DIR / "stubs.S"

NAMES = re.compile(r"^(?:egl|gl|glx|GL)[A-Za-z0-9_]*$")
# The files carry no comments of their own: they are 34k lines of table, and a
# header here would just be skipped by every reader. This docstring is the doc.
HEADER_HEAD = ["#pragma once"]
STUBS_HEAD = ["// generated by gen_proxy.py: AArch64 trampolines for the renderer proxy",
              ".text"]


def symbol_names():
    """The entry points, in the order the files list them.

    Taken from the current header so a regeneration keeps the established
    order; the list itself is the set of names the proxy has always exported.
    """
    text = SYMBOLS_H.read_text()
    entries = re.findall(r'^\s*\{"([^"]+)",\s*&([A-Za-z0-9_]+)\}', text, re.M)
    names = [name for name, _ in entries]
    if not names:
        sys.exit("proxy_symbols.h lists no symbols; refusing to generate an empty proxy")
    bad = [n for n in names if not NAMES.match(n)]
    if bad:
        sys.exit("unexpected symbol name(s): " + ", ".join(bad[:5]))
    return names


def render_header(names):
    out = list(HEADER_HEAD)
    for name in names:
        out.append("extern void *p_%s;" % name)
    out.append("typedef struct { const char *name; void **slot; } ProxySymbol;")
    out.append("static const ProxySymbol g_proxy_symbols[] = {")
    for name in names:
        out.append('  {"%s", &p_%s},' % (name, name))
    out.append("};")
    out.append("static const unsigned g_proxy_symbol_count = "
               "sizeof(g_proxy_symbols) / sizeof(g_proxy_symbols[0]);")
    return "\n".join(out) + "\n"


def render_stubs(names):
    out = list(STUBS_HEAD)
    for name in names:
        out.append(".p2align 2")
        out.append(".global %s" % name)
        out.append(".type %s,%%function" % name)
        out.append("%s:" % name)
        out.append("    adrp x16, p_%s" % name)
        out.append("    ldr x16, [x16, :lo12:p_%s]" % name)
        out.append("    br x16")
        out.append(".size %s, .-%s" % (name, name))
    out.append('.section .data,"aw"')
    for name in names:
        out.append(".p2align 2")
        out.append(".global p_%s" % name)
        out.append(".hidden p_%s" % name)
        out.append("p_%s: .quad 0" % name)
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="report files that differ instead of writing them")
    args = parser.parse_args()

    names = symbol_names()
    wanted = {SYMBOLS_H: render_header(names), STUBS_S: render_stubs(names)}
    # A sparse checkout can leave one of these out; say so instead of raising.
    stale = []
    for path, text in wanted.items():
        if not path.exists():
            print("%s is missing; run tools/gen_proxy.py" % path.relative_to(ROOT))
            stale.append(path)
        elif path.read_text() != text:
            print("%s is out of date; run tools/gen_proxy.py" % path.relative_to(ROOT))
            stale.append(path)
    if args.check:
        return 1 if stale else 0
    for path, text in wanted.items():
        path.write_text(text)
    print("wrote %d symbols to %s and %s"
          % (len(names), SYMBOLS_H.relative_to(ROOT), STUBS_S.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
