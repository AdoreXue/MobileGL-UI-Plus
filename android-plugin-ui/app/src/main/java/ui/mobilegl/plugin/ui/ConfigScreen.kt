/** 按索引里的定义渲染一组选项：标题、说明、默认值、控件类型都取自 OPTION_INDEX。 */
@Composable
private fun OptionRows(
    keys: List<String>,
    text: String,
    parsed: Map<String, String>,
    onChange: (String, String) -> Unit,
) {
    val byKey = remember { OPTION_INDEX.associateBy { it.key } }
    keys.forEach { key ->
        val meta = byKey[key] ?: return@forEach
        when {
            QUIRK_KEYS.contains(meta.key) -> OptionQuirk(
                label = meta.label,
                key = meta.key,
                text = text,
                desc = meta.desc,
                default = meta.default,
                parsed = parsed,
            ) { onChange(meta.key, it) }
            meta.isText -> OptionText(
                label = meta.label,
                key = meta.key,
                text = text,
                desc = meta.desc,
                default = meta.default,
                parsed = parsed,
            ) { onChange(meta.key, it) }
            else -> OptionToggle(
                label = meta.label,
                key = meta.key,
                text = text,
                desc = meta.desc,
                default = meta.default,
                parsed = parsed,
            ) { onChange(meta.key, onOff(it)) }
        }
    }
}
