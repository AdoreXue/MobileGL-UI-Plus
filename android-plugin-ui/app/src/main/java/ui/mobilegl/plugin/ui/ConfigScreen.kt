private const val DEFAULT_CONFIG = """# Generated by MobileGL Plugin.
# 键名与 MobileGL / SimpleFPEWrapper 的环境变量一致。
MOBILEGL_BACKEND_TYPE=DirectGLES
LIBGL_ES=3
POJAV_RENDERER=opengles3
SFPEW_EGL=libMobileGL.so
SFPEW_RELAXED_CONTEXT=0
SFPEW_NO_MULTIDRAWARRAYS=0
SFPEW_NO_LIST_BATCH=0
"""

@Composable
fun ConfigScreen(
    writer: RuntimeConfigWriter,
    status: RuntimeConfigWriter.Status,
    onStatusChanged: (RuntimeConfigWriter.Status) -> Unit,
    onMerge: (Map<String, String>) -> Unit = {},
    listState: LazyListState = rememberLazyListState(),
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    // /sdcard 是 FUSE IO，组合期间同步读会卡首帧：先显示骨架，后台读完真实文件再一次铺内容，
    // 避免先显示模板、读完又整体替换的二次跳动。
    var text by remember { mutableStateOf(DEFAULT_CONFIG) }
    var loaded by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf<String?>(null) }
    var busy by remember { mutableStateOf(false) }
    var query by remember { mutableStateOf("") }
    var confirmResetAll by remember { mutableStateOf(false) }
    var confirmTemplate by remember { mutableStateOf(false) }
    // 后端专属项默认折叠：首屏只留通用项，需要时再展开。
    var showMagma by remember { mutableStateOf(false) }
    var showEspryt by remember { mutableStateOf(false) }
    LaunchedEffect(Unit) {
        val shared = withContext(Dispatchers.IO) { writer.readShared() }
        if (shared != null) text = shared
        loaded = true
    }
    fun reload() {
        busy = true
        scope.launch {
            val shared = withContext(Dispatchers.IO) { writer.readShared() }
            text = shared ?: DEFAULT_CONFIG
            busy = false
        }
    }

    fun save() {
        val issues = validateConfig(text)
        if (issues.isNotEmpty()) {
            message = "发现 " + issues.size + " 个问题，已阻止保存：\n" + issues.joinToString("\n")
            return
        }
        busy = true
        // 解析成键值对交回 PluginApp：写入 config.json（唯一真源），再由它统一生成 runtime.conf，
        // 这样设置页开关与这里的编辑不会再互相覆盖。
        val kv = parseKeyValues(text)
        onMerge(kv)
        message = "已保存 " + kv.size + " 项（校验通过）"
        busy = false
    }
    // 整页共用一份解析结果：原始文件每敲一个字只解析一次，供所有选项读取。
    val parsed = remember(text) { parseKeyValues(text) }
    // 搜索过滤按 query 记忆，LazyColumn 重组时不重复扫索引。
    val matches = remember(query) {
        if (query.isBlank()) {
            emptyList<OptionMeta>()
        } else {
            OPTION_INDEX.filter {
                it.label.contains(query, true) || it.key.contains(query, true) || it.desc.contains(query, true)
            }
        }
    }
    // 与官方默认不同的项数：概览条与常驻保存条都用它。
    val changedTotal = remember(parsed) { OPTION_INDEX.count { optionChangedValue(it, parsed) } }
    // 骨架持续到 runtime.conf 读取完成：一步显示真实内容，不经过模板中间态。
    val ready = loaded
    val reveal = rememberContentReveal(ready)
    // 每次进入（重新组合）时列表回到顶部：骨架与内容高度差异大，
    // 保留旧滚动位置会落在内容区中间，看起来像"进了半个页面"。
    LaunchedEffect(Unit) { listState.scrollToItem(0) }
    Box(Modifier.fillMaxSize()) {
    LazyColumn(
        state = listState,
        modifier = Modifier.fillMaxSize().graphicsLayer { alpha = reveal },
        contentPadding = PaddingValues(start = 20.dp, top = 0.dp, end = 20.dp, bottom = 96.dp),
    ) {
        item { BigTitle("启动配置") }
        // 搜索框放在最前：配置项多，找东西不用先滑过整张说明卡。
        item {
            OutlinedTextField(
                value = query,
                onValueChange = { query = it },
                modifier = Modifier.fillMaxWidth().padding(top = 8.dp),
                label = { Text("搜索配置项") },
                placeholder = { Text("中文名或英文键名，如 帧在途 / FRAMES_IN_FLIGHT") },
                singleLine = true,
                trailingIcon = {
                    if (query.isNotBlank()) {
                        TextButton(onClick = { query = "" }) { Text("清除") }
                    }
                },
            )
        }
        item {
            Spacer(Modifier.height(10.dp))
            OverviewStrip(
                total = OPTION_INDEX.size,
                changed = changedTotal,
                backend = parsed["MOBILEGL_BACKEND_TYPE"] ?: "DirectGLES",
                sfpewOn = parsed["SFPEW_ENABLED"] == "1",
            )
        }
        // SFPEW 不是普通开关，先用一张独立配色的卡讲清楚是什么，再往下才是可改的配置。
        item {
            Spacer(Modifier.height(4.dp))
            Card(
                modifier = Modifier.fillMaxWidth(),
                shape = MaterialTheme.shapes.medium,
                colors = CardDefaults.cardColors(
                    containerColor = MaterialTheme.colorScheme.tertiaryContainer,
                ),
            ) {
                Column(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 14.dp)) {
                    Text(
                        "SFPEW 包装器是什么",
                        style = MaterialTheme.typography.bodyMedium,
                        fontWeight = FontWeight.SemiBold,
                    )
                    Text(
                        "给 1.16.5 及以下的老版 Minecraft 用的兼容层。老模组还在调固定管线指令" +
                            "（glBegin、glMatrixMode 这一套），现代 GLES 驱动已经不提供。SFPEW 把这些调用" +
                            "翻译成现代着色器调用，它本身不渲染，只负责把老接口接到下游后端。",
                        style = MaterialTheme.typography.labelSmall,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    Text(
                        "打开：游戏 → 代理 → SFPEW → MobileGL → GPU\n" +
                            "关闭：游戏 → 代理 → MobileGL → GPU",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    Text(
                        "玩 1.17 及以上不要打开，多包一层只会掉性能。开关与下面几项改完点「保存配置」写入，" +
                            "切换后重启游戏生效。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    // 控件等 runtime.conf 读完再画：否则先按模板渲染一遍，读完又跳一次。
                    if (BuildConfig.SFPEW_BUNDLED && ready) {
                        Spacer(Modifier.height(6.dp))
                        OptionRows(listOf("SFPEW_ENABLED"), text, parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                        OptionSelect(
                            label = "SFPEW 后端",
                            key = "SFPEW_EGL",
                            desc = "SFPEW 把这些老接口交给谁去渲染",
                            options = listOf("libMobileGL.so", "libEGL.so"),
                            value = parsed["SFPEW_EGL"] ?: "libMobileGL.so",
                            default = "libMobileGL.so",
                            parsed = parsed,
                            onSelect = { text = setKey(text, "SFPEW_EGL", it) },
                        )
                        OptionRows(SFPEW_TAIL_KEYS, text, parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                    } else if (BuildConfig.SFPEW_BUNDLED) {
                        Spacer(Modifier.height(6.dp))
                        SkeletonCard(3)
                    } else {
                        Text(
                            "当前安装包是直连版，不含 libSimpleFPEWrapper.so，无法启用。",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(top = 6.dp),
                        )
                    }
                }
            }
        }

        // 搜索结果常驻一个 item，用 AnimatedVisibility 淡入淡出：
        // LazyColumn 的增删 item 没有动画，直接 if 会让整块突然出现。
        item {
            AnimatedVisibility(
                visible = query.isNotBlank(),
                enter = fadeIn(tween(110)) + expandVertically(tween(160)),
                exit = fadeOut(tween(90)) + shrinkVertically(tween(140)),
            ) {
                Column {
                    Spacer(Modifier.height(8.dp))
                    SectionLabel("搜索结果（" + matches.size + "）")
                    InfoCard {
                        if (matches.isEmpty()) {
                            Text("没有匹配的配置项", style = MaterialTheme.typography.bodySmall)
                        }
                        OptionRows(matches.map { it.key }, text, parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                    }
                }
            }
        }
        if (!ready) {
            item {
                Spacer(Modifier.height(4.dp))
                SkeletonCard(4)
                Spacer(Modifier.height(18.dp))
                SkeletonCard(3)
                Spacer(Modifier.height(18.dp))
                SkeletonCard(4)
            }
        } else if (query.isBlank()) {
            item {
                SectionLabel("渲染后端", 1)
                InfoCard {
                    OptionSelect(
                        label = "渲染后端",
                        key = "MOBILEGL_BACKEND_TYPE",
                        desc = "DirectGLES 走 Espryt（直通 OpenGL ES，官方默认）；DirectVulkan 走 Magma（Vulkan 翻译层）。名称区分大小写，填错会让 MobileGL 没有后端可用",
                        options = listOf("DirectGLES", "DirectVulkan"),
                        value = parsed["MOBILEGL_BACKEND_TYPE"] ?: "DirectGLES",
                        default = "DirectGLES（官方默认，本插件相同）",
                        parsed = parsed,
                        onSelect = { text = setKey(text, "MOBILEGL_BACKEND_TYPE", it) },
                    )
                    Text(
                        "切换后端后，只有对应分组里的配置项会生效。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 4.dp),
                    )
                }
            }
            item {
                SectionLabel("通用配置", 11)
                InfoCard {
                    Text(
                        "所有后端通用。标「自动 / 开 / 关」的项，自动就是官方默认：不写这个键，由 MobileGL 按设备能力自行判断。改动后点「保存配置」写入。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OptionRows(COMMON_KEYS, text, parsed) { key, value -> text = setKey(text, key, value) }
                }
            }
            item {
                SectionLabel("管线", 5)
                InfoCard {
                    Text(
                        "前后端命令传递相关的进阶选项。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OptionRows(PIPE_KEYS, text, parsed) { key, value -> text = setKey(text, key, value) }
                }
            }
            item {
                SectionLabel("兼容性", 5)
                InfoCard {
                    Text(
                        "针对特定光影包或驱动的兼容处理。默认值通常可用；仅在出现具体问题时按需开启。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OptionRows(COMPAT_KEYS, text, parsed) { key, value -> text = setKey(text, key, value) }
                }
            }
            item {
                SectionLabel("诊断", 5)
                InfoCard {
                    Text(
                        "输出日志与内部校验，用于定位问题。日常开启会产生额外开销。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OptionRows(DIAG_KEYS, text, parsed) { key, value -> text = setKey(text, key, value) }
                }
            }
            item {
                SectionLabel("DirectVulkan / Magma 专用", 18)
                InfoCard {
                    Text(
                        "仅在渲染后端为 DirectVulkan 时生效。已按官方默认值配置，通常无需改动。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OutlinedButton(
                        modifier = Modifier.fillMaxWidth(),
                        onClick = { showMagma = !showMagma },
                    ) { Text(if (showMagma) "收起 18 项" else "展开 18 项") }
                    if (showMagma) {
                        Spacer(Modifier.height(4.dp))
                        OptionRows(MAGMA_KEYS, text, parsed) { key, value -> text = setKey(text, key, value) }
                    }
                }
            }
            item {
                SectionLabel("DirectGLES / Espryt 专用", 17)
                InfoCard {
                    Text(
                        "仅在渲染后端为 DirectGLES 时生效。已按官方默认值配置，通常无需改动。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OutlinedButton(
                        modifier = Modifier.fillMaxWidth(),
                        onClick = { showEspryt = !showEspryt },
                    ) { Text(if (showEspryt) "收起 17 项" else "展开 17 项") }
                    if (showEspryt) {
                        Spacer(Modifier.height(4.dp))
                        OptionRows(ESPRYT_KEYS, text, parsed) { key, value -> text = setKey(text, key, value) }
                    }
                }
            }
            item {
                SectionLabel("保存与文件")
                InfoCard {
                    Text(status.sharedPath, style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    Text(
                        if (status.sharedWritten) "已写入共享路径（启动器进程可读）" else "尚未写入共享路径：" + (status.reason ?: ""),
                        style = MaterialTheme.typography.bodySmall,
                    )
                    Text(
                        "官方 CI 的 libMobileGL.so 只读环境变量、不读此文件；本项目补丁库与后续 PanVK 驱动会读取。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    Spacer(Modifier.height(10.dp))
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        Button(enabled = !busy, onClick = { save() }) { Text("保存配置") }
                        OutlinedButton(enabled = !busy, onClick = { reload() }) { Text("重新读取") }
                    }
                    Spacer(Modifier.height(8.dp))
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        OutlinedButton(onClick = {
                            val issues = validateConfig(text)
                            message = if (issues.isEmpty()) "校验通过：所有键与取值都有效" else
                                "发现 " + issues.size + " 个问题：\n" + issues.joinToString("\n")
                        }) { Text("校验配置") }
                        OutlinedButton(onClick = { confirmTemplate = true }) { Text("恢复模板") }
                        if (!hasAllFilesAccess()) {
                            OutlinedButton(onClick = { openAllFilesSettings(context) }) { Text("授予所有文件访问权限") }
                        }
                    }
                    message?.let {
                        Spacer(Modifier.height(6.dp))
                        Text(it, style = MaterialTheme.typography.bodySmall)
                    }
                }
            }
            item {
                SectionLabel("原始文件")
                InfoCard {
                    OutlinedTextField(
                        value = text,
                        onValueChange = { text = it },
                        modifier = Modifier.fillMaxWidth().padding(vertical = 8.dp),
                        minLines = 12,
                        textStyle = MaterialTheme.typography.bodySmall,
                        label = { Text("runtime.conf") },
                    )
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        OutlinedButton(onClick = {
                            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                            clipboard.setPrimaryClip(ClipData.newPlainText("runtime.conf", text))
                        }) { Text("复制") }
                        OutlinedButton(onClick = {
                            val intent = Intent(Intent.ACTION_SEND).apply {
                                type = "text/plain"
                                putExtra(Intent.EXTRA_TEXT, text)
                            }
                            context.startActivity(Intent.createChooser(intent, "分享配置文件"))
                        }) { Text("分享") }
                    }
                }
            }
            item {
                SectionLabel("恢复默认")
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    shape = MaterialTheme.shapes.medium,
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.errorContainer),
                ) {
                    Column(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 14.dp)) {
                        Text(
                            "移除配置文件中全部配置项，保存后渲染器回到官方内置默认。",
                            style = MaterialTheme.typography.labelSmall,
                        )
                        Text(
                            "此操作不可撤销；建议先点上方「保存配置」确认当前内容已备份。",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(top = 4.dp),
                        )
                        OutlinedButton(
                            modifier = Modifier.fillMaxWidth().padding(top = 10.dp),
                            onClick = { confirmResetAll = true },
                        ) { Text("全部恢复官方默认") }
                    }
                }
            }
        }
    }
    SaveBar(
        modifier = Modifier.align(Alignment.BottomCenter),
        busy = busy,
        changed = changedTotal,
        onSave = { save() },
    )
    }
    if (confirmTemplate) {
        AlertDialog(
            onDismissRequest = { confirmTemplate = false },
            title = { Text("恢复模板？") },
            text = { Text("会用内置模板替换当前全部内容，未保存前不影响文件。") },
            confirmButton = {
                TextButton(onClick = {
                    text = DEFAULT_CONFIG
                    confirmTemplate = false
                    message = "已载入模板，记得点“保存配置”"
                }) { Text("恢复") }
            },
            dismissButton = { TextButton(onClick = { confirmTemplate = false }) { Text("取消") } },
        )
    }
    if (confirmResetAll) {
        AlertDialog(
            onDismissRequest = { confirmResetAll = false },
            title = { Text("恢复全部默认值？") },
            text = { Text("会移除当前所有配置项，保存后渲染器回到内置默认设置。此操作不可撤销。") },
            confirmButton = {
                TextButton(onClick = {
                    text = removeKeys(text, SUPPORTED_KEYS)
                    confirmResetAll = false
                    message = "已移除全部配置项，保存后回到原生默认值"
                }) { Text("恢复默认") }
            },
            dismissButton = { TextButton(onClick = { confirmResetAll = false }) { Text("取消") } },
        )
    }
}

/** 说明之后单独一行、用强调色标出官方默认值。 */
@Composable
private fun OptionDesc(desc: String, default: String) {
    if (desc.isNotBlank()) {
        Text(
            desc,
            style = MaterialTheme.typography.labelSmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
    }
    if (default.isNotBlank()) {
        Text(
            "官方默认：" + default,
            style = MaterialTheme.typography.labelSmall,
            fontWeight = FontWeight.Medium,
            color = MaterialTheme.colorScheme.primary,
            modifier = Modifier.padding(top = 2.dp),
        )
    }
}

@Composable
private fun OptionSelect(
    label: String,
    key: String = "",
    options: List<String>,
    value: String,
    desc: String = "",
    default: String = "",
    parsed: Map<String, String> = emptyMap(),
    onSelect: (String) -> Unit,
) {
    val changed = changedSelect(value, default)
    Column(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
        OptionLabel(label, changed)
        OptionDesc(desc, default)
        if (key.isNotBlank()) {
            Text(
                key,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
            )
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            options.forEach { option ->
                FilterChip(selected = option == value, onClick = { onSelect(option) }, label = { Text(option) })
            }
        }
    }
}

/**
 * 三态选项：官方用 auto / 1 / 0 表示「自动 / 强制开 / 强制关」，不写这个键就是 auto。
 * 二十多个兼容项都是这种语义，用开关只能写 0 或 1，一旦动过就回不到自动探测。
 */
@Composable
private fun OptionQuirk(
    label: String,
    key: String,
    text: String,
    desc: String = "",
    default: String = "",
    parsed: Map<String, String> = emptyMap(),
    onChange: (String) -> Unit,
) {
    val current = (parsed[key] ?: "auto").lowercase()
    val value = when (current) {
        "1", "on", "true", "yes", "forceon" -> "开"
        "0", "off", "false", "no", "forceoff" -> "关"
        else -> "自动"
    }
    val changed = changedQuirk(current, default)
    Column(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
        OptionLabel(label, changed)
        OptionDesc(desc, default)
        Text(
            key,
            style = MaterialTheme.typography.labelSmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
        )
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            listOf("自动", "开", "关").forEach { option ->
                FilterChip(
                    selected = option == value,
                    onClick = {
                        onChange(
                            when (option) {
                                "开" -> "1"
                                "关" -> "0"
                                else -> "auto"
                            },
                        )
                    },
                    label = { Text(option) },
                )
            }
        }
    }
}

@Composable
private fun OptionText(
    label: String,
    key: String,
    text: String,
    desc: String = "",
    default: String = "",
    parsed: Map<String, String> = emptyMap(),
    onChange: (String) -> Unit,
) {
    var value by remember(key, text) { mutableStateOf(parsed[key] ?: "") }
    val changed = changedText(value, default)
    Column(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
        OutlinedTextField(
            value = value,
            onValueChange = { value = it; onChange(it) },
            modifier = Modifier.fillMaxWidth(),
            label = { OptionLabel(label, changed) },
            supportingText = {
                Column {
                    OptionDesc(desc, default)
                    Text(
                        key,
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
                    )
                }
            },
            singleLine = true,
        )
    }
}

@Composable
private fun OptionToggle(
    label: String,
    key: String,
    text: String,
    desc: String = "",
    default: String = "",
    parsed: Map<String, String> = emptyMap(),
    onToggle: (Boolean) -> Unit,
) {
    val enabled = parsed[key] == "1"
    val changed = changedToggle(parsed[key] ?: "", default)
    Row(
        modifier = Modifier.fillMaxWidth().padding(vertical = 4.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(Modifier.weight(1f)) {
            OptionLabel(label, changed)
            OptionDesc(desc, default)
            Text(
                key,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
            )
        }
        Switch(checked = enabled, onCheckedChange = onToggle)
    }
}

private fun parseKeyValues(text: String): Map<String, String> {
    val out = LinkedHashMap<String, String>()
    text.lineSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .forEach { line ->
            val key = line.substringBefore('=').trim()
            val value = line.substringAfter('=').trim()
            if (key.isNotEmpty()) out[key] = value
        }
    return out
}

private fun setKey(text: String, key: String, value: String): String {
    val lines = text.lines().toMutableList()
    var replaced = false
    for (i in lines.indices) {
        val trimmed = lines[i].trim()
        if (trimmed.isEmpty() || trimmed.startsWith("#") || !trimmed.contains('=')) continue
        if (trimmed.substringBefore('=').trim() == key) {
            lines[i] = key + "=" + value
            replaced = true
            break
        }
    }
    if (!replaced) lines.add(key + "=" + value)
    return lines.joinToString("\n")
}


