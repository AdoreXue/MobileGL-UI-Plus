                SectionLabel("诊断")
                InfoCard {
            OptionToggle("管道统计", "MOBILEGL_PIPE_STATS", text, desc = "输出前后端边界的计数器：字节数、调用次数、往返次数、纹理拉取、索引镜像字节等，用来分析管线开销", default = "关", parsed = parsed) { text = setKey(text, "MOBILEGL_PIPE_STATS", onOff(it)) }
