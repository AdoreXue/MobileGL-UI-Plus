/** 搜不到时的兜底建议：先找名字相近的，再退到常用项。 */
private fun suggestOptions(query: String, context: Context): List<OptionMeta> {
    val needle = query.trim()
    if (needle.isEmpty()) return emptyList()
    val head = needle.take(2)
    val near = OPTION_INDEX.filter {
        it.key.contains(head, true) || context.getString(it.labelRes).contains(head, true)
    }.take(4)
    return near.ifEmpty { OPTION_INDEX.filter { it.key in COMMON_PICKS } }
}

/** 把命中的那段字标出来，搜索结果里一眼看见为什么命中。 */
@Composable
private fun HighlightedText(
    text: String,
    highlight: String,
    style: TextStyle,
    color: Color = Color.Unspecified,
    fontWeight: FontWeight? = null,
) {
    val needle = highlight.trim()
    val start = if (needle.isEmpty()) -1 else text.indexOf(needle, ignoreCase = true)
    if (start < 0) {
        Text(text, style = style, color = color, fontWeight = fontWeight)
        return
    }
    val accent = MaterialTheme.colorScheme.primary.copy(alpha = 0.22f)
    val marked = buildAnnotatedString {
        append(text.substring(0, start))
        withStyle(SpanStyle(background = accent, fontWeight = FontWeight.SemiBold)) {
            append(text.substring(start, start + needle.length))
        }
        append(text.substring(start + needle.length))
    }
    Text(marked, style = style, color = color, fontWeight = fontWeight)
}

/** 一组配置项：标题上的数字跟着「只看已修改」一起变，筛完没剩项就整组不画。 */
private fun LazyListScope.optionGroup(
    title: String,
    note: String,
    keys: List<String>,
    text: String,
    parsed: Map<String, String>,
    onEdit: (String, String) -> Unit,
) {
    if (keys.isEmpty()) return
    item {
        SectionLabel(title, keys.size)
        InfoCard {
            Text(
                note,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Spacer(Modifier.height(8.dp))
            OptionRows(keys, text, parsed, onChange = onEdit)
        }
    }
}

/** 按索引里的定义渲染一组选项：标题、说明、默认值、控件类型都取自 OPTION_INDEX。 */
@Composable
private fun OptionRows(
    keys: List<String>,
    text: String,
    parsed: Map<String, String>,
    highlight: String = "",
    onChange: (String, String) -> Unit,
) {
    val byKey = remember { OPTION_INDEX.associateBy { it.key } }
    val context = LocalContext.current
    fun metaLabel(meta: OptionMeta) = context.getString(meta.labelRes)
    fun metaDesc(meta: OptionMeta) = context.getString(meta.descRes)
    fun metaDefault(meta: OptionMeta) = if (meta.defaultRes == 0) "" else context.getString(meta.defaultRes)
    keys.forEach { key ->
        val meta = byKey[key] ?: return@forEach
        when {
            meta.choices.isNotEmpty() -> OptionSelect(
                label = metaLabel(meta),
                key = meta.key,
                options = meta.choices,
                value = parsed[meta.key] ?: meta.choices.first(),
                desc = metaDesc(meta),
                default = metaDefault(meta),
                parsed = parsed,
                highlight = highlight,
            ) { onChange(meta.key, it) }
            QUIRK_KEYS.contains(meta.key) -> OptionQuirk(
                label = metaLabel(meta),
                key = meta.key,
                text = text,
                desc = metaDesc(meta),
                default = metaDefault(meta),
                parsed = parsed,
                highlight = highlight,
            ) { onChange(meta.key, it) }
            meta.isText -> OptionText(
                label = metaLabel(meta),
                key = meta.key,
                text = text,
                desc = metaDesc(meta),
                default = metaDefault(meta),
                parsed = parsed,
                highlight = highlight,
            ) { onChange(meta.key, it) }
            else -> OptionToggle(
                label = metaLabel(meta),
                key = meta.key,
                text = text,
                desc = metaDesc(meta),
                default = metaDefault(meta),
                parsed = parsed,
                highlight = highlight,
            ) { onChange(meta.key, onOff(it)) }
        }
    }
}
