                    modifier = Modifier.weight(1f),
                )
                ChevronIcon(expanded = showOther, tint = MaterialTheme.colorScheme.primary, size = 16.dp)
            }
            if (showOther) {
                OptionRows(otherKeys, parsed, onChange = onEdit)
            }
        }
    }
}

/** 按索引里的定义渲染一组选项：标题、说明、默认值、控件类型都取自 OPTION_INDEX。 */
@Composable
private fun OptionRows(
    keys: List<String>,
    parsed: Map<String, String>,
    highlight: String = "",
    onChange: (String, String) -> Unit,
) {
    val byKey = remember { OPTION_INDEX.associateBy { it.key } }
    val context = LocalContext.current
    fun metaLabel(meta: OptionMeta) = context.getString(meta.labelRes)
    fun metaDesc(meta: OptionMeta) = context.getString(meta.descRes)
    fun metaDefault(meta: OptionMeta) = if (meta.defaultRes == 0) "" else context.getString(meta.defaultRes)
    keys.forEachIndexed { index, key ->
        val meta = byKey[key] ?: return@forEachIndexed
        // 组内选项之间画一条极淡的分隔线：留白压到 2dp 之后，
        // 没有这条线相邻两项会糊成一段。
        if (index > 0) DividerLine()
        when {
            meta.choices.isNotEmpty() -> OptionSelect(
                label = metaLabel(meta),
                key = meta.key,
                options = meta.choices,
                value = parsed[meta.key] ?: meta.choices.first(),
                desc = metaDesc(meta),
                default = metaDefault(meta),
                highlight = highlight,
            ) { onChange(meta.key, it) }
            QUIRK_KEYS.contains(meta.key) -> OptionQuirk(
                label = metaLabel(meta),
                key = meta.key,
                current = parsed[meta.key] ?: "auto",
                desc = metaDesc(meta),
                default = metaDefault(meta),
                highlight = highlight,
            ) { onChange(meta.key, it) }
            meta.isText -> OptionText(
                label = metaLabel(meta),
                key = meta.key,
                current = parsed[meta.key] ?: "",
                desc = metaDesc(meta),
                default = metaDefault(meta),
                highlight = highlight,
            ) { onChange(meta.key, it) }
            else -> OptionToggle(
                label = metaLabel(meta),
                key = meta.key,
                current = parsed[meta.key] ?: "",
                desc = metaDesc(meta),
                default = metaDefault(meta),
                highlight = highlight,
            ) { onChange(meta.key, onOff(it)) }
        }
    }
}
