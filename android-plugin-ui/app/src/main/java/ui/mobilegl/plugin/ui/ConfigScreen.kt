/** 三态选项的内部标记：只用来比较，显示名在下面按语言取。 */
private const val AUTO = "auto"
private const val ON = "on"
private const val OFF = "off"

/**
 * 三态选项：官方用 auto / 1 / 0 表示「自动 / 强制开 / 强制关」，不写这个键就是 auto。
 * 二十多个兼容项都是这种语义，用开关只能写 0 或 1，一旦动过就回不到自动探测。
 */
@Composable
private fun OptionQuirk(
    label: String,
    key: String,
    current: String,
    desc: String = "",
    default: String = "",
    highlight: String = "",
    onChange: (String) -> Unit,
) {
    val normalized = current.lowercase()
    // 取值仍是 auto/1/0，显示名来自资源：三枚胶囊的文字跟着语言走，比较仍走机器值。
    val value = when (normalized) {
        "1", "on", "true", "yes", "forceon" -> ON
        "0", "off", "false", "no", "forceoff" -> OFF
        else -> AUTO
    }
    val changed = changedQuirk(normalized, default)
    Column(Modifier.fillMaxWidth().padding(vertical = Space.Hair)) {
        OptionLabel(label, changed, highlight)
        OptionDesc(desc, default, highlight, changed)
        OptionKey(key)
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            listOf(AUTO, ON, OFF).forEach { option ->
                FilterChip(
                    selected = option == value,
                    onClick = {
                        onChange(
                            when (option) {
                                ON -> "1"
                                OFF -> "0"
                                else -> "auto"
                            },
                        )
                    },
                    label = {
                        Text(
                            when (option) {
                                ON -> stringResource(R.string.config_value_on)
                                OFF -> stringResource(R.string.config_value_off)
                                else -> stringResource(R.string.config_value_auto)
                            },
                        )
                    },
                )
            }
        }
    }
}

@Composable
private fun OptionText(
    label: String,
    key: String,
    current: String,
    desc: String = "",
    default: String = "",
    highlight: String = "",
    onChange: (String) -> Unit,
) {
    // 本地草稿跟着这一项自己的值走：别的项改动时这里不会被重置，也不会跟着重组。
    var value by remember(key, current) { mutableStateOf(current) }
    val changed = changedText(value, default)
    Column(Modifier.fillMaxWidth().padding(vertical = Space.Hair)) {
        OutlinedTextField(
            value = value,
            onValueChange = { value = it; onChange(it) },
            modifier = Modifier.fillMaxWidth(),
            label = { OptionLabel(label, changed, highlight) },
            supportingText = {
                Column {
                    OptionDesc(desc, default, highlight, changed)
                    OptionKey(key)
                }
            },
            singleLine = true,
        )
    }
}

