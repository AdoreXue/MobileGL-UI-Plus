private const val DEFAULT_CONFIG = """# Generated by MobileGL Plugin.
# 键名与 MobileGL / SimpleFPEWrapper 的环境变量一致。
MOBILEGL_BACKEND_TYPE=DirectGLES
LIBGL_ES=3
POJAV_RENDERER=opengles3
SFPEW_EGL=libMobileGL.so
SFPEW_RELAXED_CONTEXT=0
SFPEW_NO_MULTIDRAWARRAYS=0
SFPEW_NO_LIST_BATCH=0
"""

@Composable
fun ConfigScreen(
    writer: RuntimeConfigWriter,
    status: RuntimeConfigWriter.Status,
    onStatusChanged: (RuntimeConfigWriter.Status) -> Unit,
    onMerge: (Map<String, String>) -> Unit = {},
    listState: LazyListState = rememberLazyListState(),
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    // /sdcard 是 FUSE IO，组合期间同步读会卡首帧：先显示骨架，后台读完真实文件再一次铺内容，
    // 避免先显示模板、读完又整体替换的二次跳动。
    var text by remember { mutableStateOf(DEFAULT_CONFIG) }
    var loaded by remember { mutableStateOf(false) }
    // 结果提示带语气：校验失败必须一眼看出来，不能和「校验通过」长成同一行小字。
    var notice by remember { mutableStateOf<Notice?>(null) }
    var busy by remember { mutableStateOf(false) }
    var query by remember { mutableStateOf("") }
    var confirmResetAll by remember { mutableStateOf(false) }
    var confirmTemplate by remember { mutableStateOf(false) }
    // 后端专属项默认折叠：首屏只留通用项，需要时再展开。
    // 后端专用那两组里，当前后端用的那份总是展开；另一份默认收着，需要对照时才拉出来。
    var showOtherBackend by remember { mutableStateOf(false) }
    // SFPEW 的说明文字默认收起：它是背景知识，不是这一页要改的东西。
    var sfpewDocOpen by remember { mutableStateOf(false) }
    LaunchedEffect(Unit) {
        val shared = withContext(Dispatchers.IO) { writer.readShared() }
        if (shared != null) text = shared
        loaded = true
    }
    fun reload() {
        busy = true
        scope.launch {
            val shared = withContext(Dispatchers.IO) { writer.readShared() }
            text = shared ?: DEFAULT_CONFIG
            busy = false
        }
    }

    fun save() {
        val issues = validateConfig(text, context)
        if (issues.isNotEmpty()) {
            notice = Notice(
                context.getString(R.string.config_save_blocked, issues.size, issues.joinToString("\n")),
                NoteTone.Bad,
            )
            return
        }
        // 解析成键值对交回 PluginApp：写入 config.json（唯一真源），再由它统一生成 runtime.conf，
        // 这样设置页开关与这里的编辑不会再互相覆盖。写盘在那边异步进行，结果由状态卡展示，
        // 所以这里不再用一个永远不会渲染的 busy 假装「保存中」。
        val kv = parseKeyValues(text)
        onMerge(kv)
        notice = Notice(context.getString(R.string.config_submitted, kv.size), NoteTone.Good)
    }
    // 整页共用一份解析结果：原始文件每敲一个字只解析一次，供所有选项读取。
    val parsed = remember(text) { parseKeyValues(text) }
    // 搜索过滤按 query 记忆，LazyColumn 重组时不重复扫索引。
    val matches = remember(query, context) {
        if (query.isBlank()) {
            emptyList<OptionMeta>()
        } else {
            OPTION_INDEX.filter {
                it.key.contains(query, true) ||
                    context.getString(it.labelRes).contains(query, true) ||
                    context.getString(it.descRes).contains(query, true)
            }
        }
    }
    val wide = LocalWindowWidth.current.twoColumns
    // 后端专用那两组：当前后端用的那份直接铺开，另一份收在同一个卡里。
    val activeBackend = parsed["MOBILEGL_BACKEND_TYPE"] ?: "DirectGLES"
    val activeBackendKeys = if (activeBackend == "DirectVulkan") MAGMA_KEYS else ESPRYT_KEYS
    val otherBackendKeys = if (activeBackend == "DirectVulkan") ESPRYT_KEYS else MAGMA_KEYS
    val backendLabel = stringResource(R.string.config_group_magma)
    val glesLabel = stringResource(R.string.config_group_espryt)
    val activeBackendLabel = if (activeBackend == "DirectVulkan") backendLabel else glesLabel
    val otherBackendLabel = if (activeBackend == "DirectVulkan") glesLabel else backendLabel
    // 与官方默认不同的项数：概览条和保存条都用它。
    // 后端在「渲染」页切换，不在这张索引里；但它偏离打包默认值时同样是「改过」，
    // 不算进来的话概览会一边写着 DirectVulkan 一边说「全部与官方默认一致」。
    val packagedBackend = context.getString(R.string.mobilegl_default_backend)
    val backendChanged = activeBackend != packagedBackend
    val changedTotal = remember(parsed, backendChanged) {
        OPTION_INDEX.count { optionChangedValue(it, parsed) } + if (backendChanged) 1 else 0
    }
    // 「只看已修改」：只留下跟官方默认不一样的项，改完自查一遍用。
    var onlyChanged by remember { mutableStateOf(false) }
    val changedKeySet = remember(parsed) {
        OPTION_INDEX.filter { optionChangedValue(it, parsed) }.map { it.key }.toSet()
    }
    fun visible(keys: List<String>): List<String> = if (onlyChanged) keys.filter { it in changedKeySet } else keys
    // 搜索结果同样受「只看已修改」影响，两个入口的规则保持一致。
    val resultMatches = if (onlyChanged) matches.filter { it.key in changedKeySet } else matches
    // 原始文件区默认收起：整份配置很长，平时用不到全文编辑。
    var rawOpen by remember { mutableStateOf(false) }
    // 没有改动时不占位，保存条只在需要时浮出来。
    val showSaveBar = changedTotal > 0 || busy
    // 搜索结果里点「跳到该组」后只显示那一组，顶上一枚胶囊可以退回全部。
    var jumpGroup by remember { mutableStateOf<String?>(null) }
    fun groupShown(section: String): Boolean = jumpGroup == null || jumpGroup == section
    fun jumpTo(section: String, key: String? = null) {
        // 搜到的那一项若在「当前后端不用」的那半组里，跳过去要顺手把它展开，否则落地是空的。
        if (section == SECTION_BACKEND && key != null && !activeBackendKeys.contains(key)) {
            showOtherBackend = true
        }
        jumpGroup = section.ifBlank { null }
        query = ""
        onlyChanged = false
    }
    // 骨架持续到 runtime.conf 读取完成：一步显示真实内容，不经过模板中间态。
    val ready = loaded
    val reveal = rememberContentReveal(ready)
    // 每次进入（重新组合）时列表回到顶部：骨架与内容高度差异大，
    // 保留旧滚动位置会落在内容区中间，看起来像"进了半个页面"。
    LaunchedEffect(Unit) { listState.scrollToItem(0) }
    // 跳到某组后列表会重建，滚回顶部才看得到那组的标题。
    LaunchedEffect(jumpGroup) { if (jumpGroup != null) listState.scrollToItem(0) }
    Box(Modifier.fillMaxSize()) {
        // 顶部固定区（搜索＋筛选）和列表放在同一个纵向容器里，列表才能用 weight 吃掉剩余高度。
        Column(Modifier.fillMaxSize()) {
        Column(
            Modifier
                .fillMaxWidth()
                .padding(horizontal = Space.Page)
                .padding(top = Space.Md, bottom = Space.Sm),
        ) {
            // 子页顶栏已经写着「启动配置」，这里不再重复标题；
            // 项数与概览卡里的「配置项」是同一个数，所以也只在那里出现一次。
            // 搜索框自己一行，筛选胶囊另起一行：原来两者挤在同一条 46dp 里，
            // 而清除按钮和胶囊的最小触控区是 48dp，控件比容器还高，上下必然贴边。
            Surface(
                shape = RoundedCornerShape(50),
                color = MaterialTheme.colorScheme.surfaceContainer,
                modifier = Modifier.fillMaxWidth(),
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .heightIn(min = 48.dp)
                        .padding(start = Space.Lg, end = Space.Sm),
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    Icon(
                        Icons.Filled.Search,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.size(18.dp),
                    )
                    Spacer(Modifier.width(Space.Md))
                    BasicTextField(
                        value = query,
                        onValueChange = { query = it },
                        modifier = Modifier.weight(1f),
                        singleLine = true,
                        textStyle = MaterialTheme.typography.bodyMedium.copy(
                            color = MaterialTheme.colorScheme.onSurface,
                        ),
                        cursorBrush = SolidColor(MaterialTheme.colorScheme.primary),
                        decorationBox = { inner ->
                            if (query.isBlank()) {
                                Text(
                                    stringResource(R.string.config_search_hint),
                                    style = MaterialTheme.typography.bodyMedium,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                            }
                            inner()
                        },
                    )
                    if (query.isNotBlank()) {
                        IconButton(onClick = { query = "" }) {
                            Icon(
                                Icons.Filled.Clear,
                                contentDescription = stringResource(R.string.config_search_clear),
                                tint = MaterialTheme.colorScheme.onSurfaceVariant,
                                modifier = Modifier.size(18.dp),
                            )
                        }
                    } else {
                        // 没有文字时不占位，但右侧留出同样的内边距，输入区不会贴到圆角上。
                        Spacer(Modifier.width(Space.Xs))
                    }
                }
            }
            Spacer(Modifier.height(Space.Sm))
            // 筛选胶囊单独一行，与「跳到该组」那类胶囊一样高，不再被搜索框压着。
            Row(verticalAlignment = Alignment.CenterVertically) {
                FilterChip(
                    selected = onlyChanged,
                    onClick = { onlyChanged = !onlyChanged },
                    enabled = changedTotal > 0 || onlyChanged,
                    label = {
                        Text(
                            if (changedTotal > 0) {
                                stringResource(R.string.config_filter_changed_count, changedTotal)
                            } else {
                                stringResource(R.string.config_filter_only_changed)
                            },
                        )
                    },
                )
            }
        }
    LazyColumn(
        state = listState,
        modifier = Modifier.fillMaxWidth().weight(1f).graphicsLayer {
            alpha = reveal.alpha
            translationY = reveal.rise.toPx()
        },
        contentPadding = PaddingValues(
            start = 20.dp,
            top = 0.dp,
            end = 20.dp,
            bottom = if (showSaveBar) 96.dp else 24.dp,
        ),
    ) {
        item {
            Spacer(Modifier.height(10.dp))
            OverviewStrip(
                total = OPTION_INDEX.size,
                changed = changedTotal,
                backend = activeBackend,
                sfpewOn = parsed["SFPEW_ENABLED"] == "1",
            )
        }
        // SFPEW 不是普通开关，先用一张独立配色的卡讲清楚是什么，再往下才是可改的配置。
        // 「只看已修改」时，这张说明卡也只在 SFPEW 相关项确实改过时才留下。
        val sfpewDirty = "SFPEW_ENABLED" in changedKeySet || SFPEW_TAIL_KEYS.any { it in changedKeySet }
        if ((!onlyChanged || sfpewDirty) && groupShown(SECTION_SFPEW)) item(key = "sfpew") {
            Spacer(Modifier.height(4.dp))
            Card(
                modifier = Modifier.fillMaxWidth(),
                shape = MaterialTheme.shapes.medium,
                // 半透明上色：整块高饱和绿把首屏最亮的位置占了，读起来像另一个应用的面板。
                colors = CardDefaults.cardColors(
                    containerColor = MaterialTheme.colorScheme.tertiaryContainer.copy(alpha = 0.5f),
                ),
            ) {
                Column(Modifier.fillMaxWidth().padding(horizontal = Space.Lg, vertical = Space.Md)) {
                    // 三段解释加起来四百多 dp，是首屏最亮最大的一块，却只是背景知识。
                    // 收起时只留标题和一句摘要，说明按需展开；要改的东西一直在。
                    FoldableNote(
                        summary = stringResource(R.string.config_sfpew_title),
                        detail = stringResource(R.string.config_sfpew_intro) + "\n\n" +
                            stringResource(R.string.config_sfpew_chain) + "\n\n" +
                            stringResource(R.string.config_sfpew_advice),
                        expanded = sfpewDocOpen,
                        onToggle = { sfpewDocOpen = it },
                        expandLabel = stringResource(R.string.config_sfpew_why),
                        summaryStyle = MaterialTheme.typography.bodyMedium,
                        summaryColor = MaterialTheme.colorScheme.onSurface,
                        collapsedLabel = stringResource(R.string.config_sfpew_hide),
                    )
                    Spacer(Modifier.height(Space.Xs))
                    // 控件等 runtime.conf 读完再画：否则先按模板渲染一遍，读完又跳一次。
                    if (BuildConfig.SFPEW_BUNDLED && ready) {
                        Spacer(Modifier.height(6.dp))
                        OptionRows(listOf("SFPEW_ENABLED"), parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                        OptionSelect(
                            label = stringResource(R.string.config_sfpew_backend),
                            key = "SFPEW_EGL",
                            desc = stringResource(R.string.config_sfpew_backend_desc),
                            options = listOf("libMobileGL.so", "libEGL.so"),
                            value = parsed["SFPEW_EGL"] ?: "libMobileGL.so",
                            default = "libMobileGL.so",
                            onSelect = { text = setKey(text, "SFPEW_EGL", it) },
                        )
                        OptionRows(SFPEW_TAIL_KEYS, parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                    } else if (BuildConfig.SFPEW_BUNDLED) {
                        Spacer(Modifier.height(6.dp))
                        SkeletonCard(3)
                    } else {
                        Text(
                            stringResource(R.string.config_sfpew_not_bundled),
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(top = 6.dp),
                        )
                    }
                }
            }
        }

        // 搜索结果常驻一个 item，用 AnimatedVisibility 淡入淡出：
        // LazyColumn 的增删 item 没有动画，直接 if 会让整块突然出现。
        item(key = "search") {
            AnimatedVisibility(
                visible = query.isNotBlank(),
                enter = Motion.foldEnter(),
                exit = Motion.foldExit(),
            ) {
                Column {
                    Spacer(Modifier.height(8.dp))
                    SectionLabel(stringResource(R.string.config_search_results, resultMatches.size))
                    InfoCard {
                        if (resultMatches.isEmpty()) {
                            EmptyState(
                                icon = Icons.Filled.Search,
                                title = stringResource(R.string.config_search_empty_title),
                                body = stringResource(R.string.config_search_empty_body),
                            )
                            val hints = suggestOptions(query, context)
                            if (hints.isNotEmpty()) {
                                Text(
                                    stringResource(R.string.config_search_try),
                                    modifier = Modifier.padding(top = 10.dp),
                                    style = MaterialTheme.typography.labelSmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                                Row(
                                    modifier = Modifier.fillMaxWidth().padding(top = 6.dp).horizontalScroll(rememberScrollState()),
                                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                                ) {
                                    hints.forEach { hint ->
                                        FilterChip(
                                            selected = false,
                                            onClick = { query = context.getString(hint.labelRes) },
                                            label = {
                                                Text(
                                                    context.getString(hint.labelRes),
                                                    style = MaterialTheme.typography.labelMedium,
                                                )
                                            },
                                        )
                                    }
                                }
                            }
                        }
                        resultMatches.forEachIndexed { index, meta ->
                            val section = OPTION_SECTION[meta.key].orEmpty()
                            if (index > 0) DividerLine()
                            Row(
                                modifier = Modifier.fillMaxWidth().padding(top = 8.dp),
                                verticalAlignment = Alignment.CenterVertically,
                            ) {
                                Text(
                                    sectionLabel(section),
                                    style = MaterialTheme.typography.labelSmall,
                                    color = MaterialTheme.colorScheme.primary,
                                )
                                Spacer(Modifier.weight(1f))
                                if (section.isNotBlank()) {
                                    Text(
                                        stringResource(R.string.config_jump_group),
                                        modifier = Modifier
                                            .minimumInteractiveComponentSize()
                                            .clickable(
                                                onClickLabel = stringResource(R.string.config_jump_group_label),
                                                role = Role.Button,
                                            ) { jumpTo(section, meta.key) },
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                                    )
                                }
                            }
                            OptionRows(listOf(meta.key), parsed, highlight = query) { key, value ->
                                text = setKey(text, key, value)
                            }
                        }
                    }
                }
            }
        }
        if (!ready) {
            item {
                FillSkeleton(cards = 5)
            }
        } else if (query.isBlank()) {
            if (jumpGroup != null) {
                val group = jumpGroup
                item {
                    Row(
                        modifier = Modifier.fillMaxWidth().clickable { jumpGroup = null }.padding(vertical = 10.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Text(
                            stringResource(R.string.config_back_to_all),
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.primary,
                        )
                        Spacer(Modifier.weight(1f))
                        Text(
                            group?.let { sectionLabel(it) } ?: "",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
            }
            if (onlyChanged && changedTotal == 0) {
                item {
                    InfoCard {
                        Text(
                            stringResource(R.string.config_no_changes),
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
            }
            if (wide) {
                // 宽屏：左侧是「所有后端通用」的三组，右侧是「只对当前后端生效」那组。
                item(key = "groups-wide") {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(Space.Xl),
                    ) {
                        Column(Modifier.weight(1f)) {
                            OptionGroupBlock(
                                SECTION_COMMON,
                                R.string.config_section_common_note,
                                if (groupShown(SECTION_COMMON)) visible(COMMON_KEYS) else emptyList(),
                                parsed,
                            ) { key, value -> text = setKey(text, key, value) }
                            OptionGroupBlock(
                                SECTION_PIPE,
                                R.string.config_section_pipe_note,
                                if (groupShown(SECTION_PIPE)) visible(PIPE_KEYS) else emptyList(),
                                parsed,
                            ) { key, value -> text = setKey(text, key, value) }
                            OptionGroupBlock(
                                SECTION_COMPAT,
                                R.string.config_section_compat_note,
                                if (groupShown(SECTION_COMPAT)) visible(COMPAT_KEYS) else emptyList(),
                                parsed,
                            ) { key, value -> text = setKey(text, key, value) }
                            OptionGroupBlock(
                                SECTION_DIAG,
                                R.string.config_section_diag_note,
                                if (groupShown(SECTION_DIAG)) visible(DIAG_KEYS) else emptyList(),
                                parsed,
                            ) { key, value -> text = setKey(text, key, value) }
                        }
                        Column(Modifier.weight(1f)) {
                            if (groupShown(SECTION_BACKEND) && visible(activeBackendKeys).isNotEmpty()) {
                                BackendSpecificCard(
                                    activeKeys = visible(activeBackendKeys),
                                    otherKeys = visible(otherBackendKeys),
                                    activeLabel = activeBackendLabel,
                                    otherLabel = otherBackendLabel,
                                    showOther = showOtherBackend,
