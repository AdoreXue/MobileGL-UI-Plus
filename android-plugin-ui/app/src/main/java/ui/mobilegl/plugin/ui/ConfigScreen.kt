            Text(desc, style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
        if (key.isNotBlank()) {
            Text(
                key,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
            )
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            options.forEach { option ->
                FilterChip(selected = option == value, onClick = { onSelect(option) }, label = { Text(option) })
            }
        }
    }
}

@Composable
private fun OptionText(label: String, key: String, text: String, desc: String = "", onChange: (String) -> Unit) {
    var value by remember(key, text) { mutableStateOf(readKey(text, key, "")) }
    Column(Modifier.fillMaxWidth().padding(vertical = 4.dp)) {
        OutlinedTextField(
            value = value,
            onValueChange = { value = it; onChange(it) },
            modifier = Modifier.fillMaxWidth(),
            label = { Text(label) },
            supportingText = {
                Column {
                    if (desc.isNotBlank()) {
                        Text(
                            desc,
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                    Text(
                        key,
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
                    )
                }
            },
            singleLine = true,
        )
    }
}

@Composable
private fun OptionToggle(label: String, key: String, text: String, desc: String = "", onToggle: (Boolean) -> Unit) {
    val enabled = readKey(text, key, "0") == "1"
    Row(
        modifier = Modifier.fillMaxWidth().padding(vertical = 4.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(Modifier.weight(1f)) {
            Text(label, style = MaterialTheme.typography.bodySmall)
            if (desc.isNotBlank()) {
                Text(
                    desc,
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
            Text(
                key,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
            )
        }
        Switch(checked = enabled, onCheckedChange = onToggle)
    }
}

private fun parseKeyValues(text: String): Map<String, String> {
    val out = LinkedHashMap<String, String>()
    text.lineSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .forEach { line ->
            val key = line.substringBefore('=').trim()
            val value = line.substringAfter('=').trim()
            if (key.isNotEmpty()) out[key] = value
        }
    return out
}

private fun readKey(text: String, key: String, fallback: String): String =
    text.lineSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .map { it.substringBefore('=').trim() to it.substringAfter('=').trim() }
        .firstOrNull { it.first == key }?.second ?: fallback

private fun setKey(text: String, key: String, value: String): String {
    val lines = text.lines().toMutableList()
    var replaced = false
    for (i in lines.indices) {
        val trimmed = lines[i].trim()
        if (trimmed.isEmpty() || trimmed.startsWith("#") || !trimmed.contains('=')) continue
        if (trimmed.substringBefore('=').trim() == key) {
            lines[i] = key + "=" + value
            replaced = true
            break
        }
    }
    if (!replaced) lines.add(key + "=" + value)
    return lines.joinToString("\n")
}

