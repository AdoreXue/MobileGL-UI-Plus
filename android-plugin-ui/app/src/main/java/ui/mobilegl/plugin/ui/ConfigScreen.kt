private fun parseKeyValues(text: String): Map<String, String> {
    val out = LinkedHashMap<String, String>()
    text.lineSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .forEach { line ->
            val key = line.substringBefore('=').trim()
            val value = line.substringAfter('=').trim()
            if (key.isNotEmpty()) out[key] = value
        }
    return out
}

private fun readKey(text: String, key: String, fallback: String): String =
    text.lineSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .map { it.substringBefore('=').trim() to it.substringAfter('=').trim() }
        .firstOrNull { it.first == key }?.second ?: fallback

private fun setKey(text: String, key: String, value: String): String {
    val lines = text.lines().toMutableList()
    var replaced = false
    for (i in lines.indices) {
        val trimmed = lines[i].trim()
        if (trimmed.isEmpty() || trimmed.startsWith("#") || !trimmed.contains('=')) continue
        if (trimmed.substringBefore('=').trim() == key) {
            lines[i] = key + "=" + value
            replaced = true
            break
        }
    }
    if (!replaced) lines.add(key + "=" + value)
    return lines.joinToString("\n")
}

