private const val DEFAULT_CONFIG = """# Generated by MobileGL Plugin.
# 键名与 MobileGL / SimpleFPEWrapper 的环境变量一致。
MOBILEGL_BACKEND_TYPE=DirectGLES
LIBGL_ES=3
POJAV_RENDERER=opengles3
SFPEW_EGL=libMobileGL.so
SFPEW_RELAXED_CONTEXT=0
SFPEW_NO_MULTIDRAWARRAYS=0
SFPEW_NO_LIST_BATCH=0
"""

@Composable
fun ConfigScreen(
    writer: RuntimeConfigWriter,
    status: RuntimeConfigWriter.Status,
    onStatusChanged: (RuntimeConfigWriter.Status) -> Unit,
    onMerge: (Map<String, String>) -> Unit = {},
    listState: LazyListState = rememberLazyListState(),
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    // /sdcard 是 FUSE IO，组合期间同步读会卡首帧：先显示骨架，后台读完真实文件再一次铺内容，
    // 避免先显示模板、读完又整体替换的二次跳动。
    var text by remember { mutableStateOf(DEFAULT_CONFIG) }
    var loaded by remember { mutableStateOf(false) }
    // 结果提示带语气：校验失败必须一眼看出来，不能和「校验通过」长成同一行小字。
    var notice by remember { mutableStateOf<Notice?>(null) }
    var busy by remember { mutableStateOf(false) }
    var query by remember { mutableStateOf("") }
    var confirmResetAll by remember { mutableStateOf(false) }
    var confirmTemplate by remember { mutableStateOf(false) }
    // 后端专属项默认折叠：首屏只留通用项，需要时再展开。
    var showMagma by remember { mutableStateOf(false) }
    var showEspryt by remember { mutableStateOf(false) }
    LaunchedEffect(Unit) {
        val shared = withContext(Dispatchers.IO) { writer.readShared() }
        if (shared != null) text = shared
        loaded = true
    }
    fun reload() {
        busy = true
        scope.launch {
            val shared = withContext(Dispatchers.IO) { writer.readShared() }
            text = shared ?: DEFAULT_CONFIG
            busy = false
        }
    }

    fun save() {
        val issues = validateConfig(text)
        if (issues.isNotEmpty()) {
            notice = Notice(
                "发现 " + issues.size + " 个问题，已阻止保存：\n" + issues.joinToString("\n"),
                NoteTone.Bad,
            )
            return
        }
        // 解析成键值对交回 PluginApp：写入 config.json（唯一真源），再由它统一生成 runtime.conf，
        // 这样设置页开关与这里的编辑不会再互相覆盖。写盘在那边异步进行，结果由状态卡展示，
        // 所以这里不再用一个永远不会渲染的 busy 假装「保存中」。
        val kv = parseKeyValues(text)
        onMerge(kv)
        notice = Notice("已提交 " + kv.size + " 项（校验通过），写入结果见上方状态卡", NoteTone.Good)
    }
    // 整页共用一份解析结果：原始文件每敲一个字只解析一次，供所有选项读取。
    val parsed = remember(text) { parseKeyValues(text) }
    // 搜索过滤按 query 记忆，LazyColumn 重组时不重复扫索引。
    val matches = remember(query, context) {
        if (query.isBlank()) {
            emptyList<OptionMeta>()
        } else {
            OPTION_INDEX.filter {
                it.key.contains(query, true) ||
                    context.getString(it.labelRes).contains(query, true) ||
                    context.getString(it.descRes).contains(query, true)
            }
        }
    }
    // 与官方默认不同的项数：概览条和保存条都用它。
    val changedTotal = remember(parsed) { OPTION_INDEX.count { optionChangedValue(it, parsed) } }
    // 「只看已修改」：只留下跟官方默认不一样的项，改完自查一遍用。
    var onlyChanged by remember { mutableStateOf(false) }
    val changedKeySet = remember(parsed) {
        OPTION_INDEX.filter { optionChangedValue(it, parsed) }.map { it.key }.toSet()
    }
    fun visible(keys: List<String>): List<String> = if (onlyChanged) keys.filter { it in changedKeySet } else keys
    // 搜索结果同样受「只看已修改」影响，两个入口的规则保持一致。
    val resultMatches = if (onlyChanged) matches.filter { it.key in changedKeySet } else matches
    // 原始文件区默认收起：整份配置很长，平时用不到全文编辑。
    var rawOpen by remember { mutableStateOf(false) }
    // 没有改动时不占位，保存条只在需要时浮出来。
    val showSaveBar = changedTotal > 0 || busy
    // 搜索结果里点「跳到该组」后只显示那一组，顶上一枚胶囊可以退回全部。
    var jumpGroup by remember { mutableStateOf<String?>(null) }
    fun groupShown(section: String): Boolean = jumpGroup == null || jumpGroup == section
    fun jumpTo(section: String) {
        if (section == "DirectVulkan / Magma 专用") showMagma = true
        if (section == "DirectGLES / Espryt 专用") showEspryt = true
        jumpGroup = section.ifBlank { null }
        query = ""
        onlyChanged = false
    }
    // 骨架持续到 runtime.conf 读取完成：一步显示真实内容，不经过模板中间态。
    val ready = loaded
    val reveal = rememberContentReveal(ready)
    // 每次进入（重新组合）时列表回到顶部：骨架与内容高度差异大，
    // 保留旧滚动位置会落在内容区中间，看起来像"进了半个页面"。
    LaunchedEffect(Unit) { listState.scrollToItem(0) }
    // 跳到某组后列表会重建，滚回顶部才看得到那组的标题。
    LaunchedEffect(jumpGroup) { if (jumpGroup != null) listState.scrollToItem(0) }
    Box(Modifier.fillMaxSize()) {
        // 顶部固定区（标题 + 搜索）和列表放在同一个纵向容器里，列表才能用 weight 吃掉剩余高度。
        Column(Modifier.fillMaxSize()) {
        Column(Modifier.fillMaxWidth().padding(horizontal = 20.dp).padding(top = 10.dp, bottom = 8.dp)) {
            // 标题在最顶：搜索框不再压在页面标题上面。
            Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                Text(
                    "启动配置",
                    modifier = Modifier.weight(1f),
                    style = MaterialTheme.typography.headlineSmall,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface,
                )
                Text(
                    if (onlyChanged) "已改 " + changedTotal + " / " + OPTION_INDEX.size else "共 " + OPTION_INDEX.size + " 项",
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
            Spacer(Modifier.height(10.dp))
            // 一行搞定：搜索、清除、「只看已修改」。
            Surface(
                shape = RoundedCornerShape(50),
                color = MaterialTheme.colorScheme.surfaceContainer,
                modifier = Modifier.fillMaxWidth(),
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth().height(46.dp).padding(horizontal = 14.dp),
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    Icon(
                        Icons.Filled.Search,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.size(18.dp),
                    )
                    Spacer(Modifier.width(10.dp))
                    BasicTextField(
                        value = query,
                        onValueChange = { query = it },
                        modifier = Modifier.weight(1f),
                        singleLine = true,
                        textStyle = MaterialTheme.typography.bodyMedium.copy(color = MaterialTheme.colorScheme.onSurface),
                        cursorBrush = SolidColor(MaterialTheme.colorScheme.primary),
                        decorationBox = { inner ->
                            if (query.isBlank()) {
                                Text(
                                    "搜索配置项或键名",
                                    style = MaterialTheme.typography.bodyMedium,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                            }
                            inner()
                        },
                    )
                    if (query.isNotBlank()) {
                        Spacer(Modifier.width(8.dp))
                        Box(
                            modifier = Modifier
                                .size(48.dp)
                                .clickable(onClickLabel = "清除搜索", role = Role.Button) { query = "" },
                            contentAlignment = Alignment.Center,
                        ) {
                            Icon(
                                Icons.Filled.Clear,
                                contentDescription = null,
                                tint = MaterialTheme.colorScheme.onSurfaceVariant,
                                modifier = Modifier.size(18.dp),
                            )
                        }
                    }
                    Spacer(Modifier.width(10.dp))
                    Text(
                        if (changedTotal > 0) "改动 " + changedTotal else "只看改动",
                        modifier = Modifier
                            .clip(RoundedCornerShape(50))
                            .background(
                                if (onlyChanged) MaterialTheme.colorScheme.primary
                                else MaterialTheme.colorScheme.surface,
                            )
                            .minimumInteractiveComponentSize()
                            .clickable(
                                enabled = changedTotal > 0 || onlyChanged,
                                onClickLabel = "只看改动过的项",
                                role = Role.Button,
                            ) { onlyChanged = !onlyChanged }
                            .padding(horizontal = 10.dp, vertical = 4.dp),
                        style = MaterialTheme.typography.labelSmall,
                        color = if (onlyChanged) {
                            MaterialTheme.colorScheme.onPrimary
                        } else {
                            MaterialTheme.colorScheme.onSurfaceVariant
                        },
                    )
                }
            }
        }
    LazyColumn(
        state = listState,
        modifier = Modifier.fillMaxWidth().weight(1f).graphicsLayer {
            alpha = reveal.alpha
            translationY = reveal.rise.toPx()
        },
        contentPadding = PaddingValues(
            start = 20.dp,
            top = 0.dp,
            end = 20.dp,
            bottom = if (showSaveBar) 96.dp else 24.dp,
        ),
    ) {
        item {
            Spacer(Modifier.height(10.dp))
            OverviewStrip(
                total = OPTION_INDEX.size,
                changed = changedTotal,
                backend = parsed["MOBILEGL_BACKEND_TYPE"] ?: "DirectGLES",
                sfpewOn = parsed["SFPEW_ENABLED"] == "1",
            )
        }
        // SFPEW 不是普通开关，先用一张独立配色的卡讲清楚是什么，再往下才是可改的配置。
        // 「只看已修改」时，这张说明卡也只在 SFPEW 相关项确实改过时才留下。
        val sfpewDirty = "SFPEW_ENABLED" in changedKeySet || SFPEW_TAIL_KEYS.any { it in changedKeySet }
        if ((!onlyChanged || sfpewDirty) && groupShown("SFPEW")) item {
            Spacer(Modifier.height(4.dp))
            Card(
                modifier = Modifier.fillMaxWidth(),
                shape = MaterialTheme.shapes.medium,
                colors = CardDefaults.cardColors(
                    containerColor = MaterialTheme.colorScheme.tertiaryContainer,
                ),
            ) {
                Column(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 14.dp)) {
                    Text(
                        "SFPEW 包装器是什么",
                        style = MaterialTheme.typography.bodyMedium,
                        fontWeight = FontWeight.SemiBold,
                    )
                    Text(
                        "给 1.16.5 及以下的老版 Minecraft 用的兼容层。老模组还在调固定管线指令" +
                            "（glBegin、glMatrixMode 这一套），现代 GLES 驱动已经不提供。SFPEW 把这些调用" +
                            "翻译成现代着色器调用，它本身不渲染，只负责把老接口接到下游后端。",
                        style = MaterialTheme.typography.labelSmall,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    Text(
                        "打开：游戏 → 代理 → SFPEW → MobileGL → GPU\n" +
                            "关闭：游戏 → 代理 → MobileGL → GPU",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    Text(
                        "玩 1.17 及以上不要打开，多包一层只会掉性能。开关与下面几项改完点「保存配置」写入，" +
                            "切换后重启游戏生效。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 6.dp),
                    )
                    // 控件等 runtime.conf 读完再画：否则先按模板渲染一遍，读完又跳一次。
                    if (BuildConfig.SFPEW_BUNDLED && ready) {
                        Spacer(Modifier.height(6.dp))
                        OptionRows(listOf("SFPEW_ENABLED"), text, parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                        OptionSelect(
                            label = "SFPEW 后端",
                            key = "SFPEW_EGL",
                            desc = "SFPEW 把这些老接口交给谁去渲染",
                            options = listOf("libMobileGL.so", "libEGL.so"),
                            value = parsed["SFPEW_EGL"] ?: "libMobileGL.so",
                            default = "libMobileGL.so",
                            parsed = parsed,
                            onSelect = { text = setKey(text, "SFPEW_EGL", it) },
                        )
                        OptionRows(SFPEW_TAIL_KEYS, text, parsed) { key, value ->
                            text = setKey(text, key, value)
                        }
                    } else if (BuildConfig.SFPEW_BUNDLED) {
                        Spacer(Modifier.height(6.dp))
                        SkeletonCard(3)
                    } else {
                        Text(
                            "当前安装包是直连版，不含 libSimpleFPEWrapper.so，无法启用。",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.padding(top = 6.dp),
                        )
                    }
                }
            }
        }

        // 搜索结果常驻一个 item，用 AnimatedVisibility 淡入淡出：
        // LazyColumn 的增删 item 没有动画，直接 if 会让整块突然出现。
        item {
            AnimatedVisibility(
                visible = query.isNotBlank(),
                enter = Motion.foldEnter(),
                exit = Motion.foldExit(),
            ) {
                Column {
                    Spacer(Modifier.height(8.dp))
                    SectionLabel("搜索结果（" + resultMatches.size + "）")
                    InfoCard {
                        if (resultMatches.isEmpty()) {
                            EmptyState(
                                icon = Icons.Filled.Search,
                                title = "没有匹配的配置项",
                                body = "换个说法或直接搜键名试试，比如 SFPEW、ANGLE、缓存。",
                            )
                            val hints = suggestOptions(query, context)
                            if (hints.isNotEmpty()) {
                                Text(
                                    "试试这些：",
                                    modifier = Modifier.padding(top = 10.dp),
                                    style = MaterialTheme.typography.labelSmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                                Row(
                                    modifier = Modifier.fillMaxWidth().padding(top = 6.dp).horizontalScroll(rememberScrollState()),
                                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                                ) {
                                    hints.forEach { hint ->
                                        FilterChip(
                                            selected = false,
                                            onClick = { query = context.getString(hint.labelRes) },
                                            label = {
                                                Text(
                                                    context.getString(hint.labelRes),
                                                    style = MaterialTheme.typography.labelMedium,
                                                )
                                            },
                                        )
                                    }
                                }
                            }
                        }
                        resultMatches.forEachIndexed { index, meta ->
                            val section = OPTION_SECTION[meta.key].orEmpty()
                            if (index > 0) DividerLine()
                            Row(
                                modifier = Modifier.fillMaxWidth().padding(top = 8.dp),
                                verticalAlignment = Alignment.CenterVertically,
                            ) {
                                Text(
                                    section.ifBlank { "其他" },
                                    style = MaterialTheme.typography.labelSmall,
                                    color = MaterialTheme.colorScheme.primary,
                                )
                                Spacer(Modifier.weight(1f))
                                if (section.isNotBlank()) {
                                    Text(
                                        "跳到该组 ›",
                                        modifier = Modifier
                                            .minimumInteractiveComponentSize()
                                            .clickable(
                                                onClickLabel = "跳到该组",
                                                role = Role.Button,
                                            ) { jumpTo(section) },
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                                    )
                                }
                            }
                            OptionRows(listOf(meta.key), text, parsed, highlight = query) { key, value ->
                                text = setKey(text, key, value)
                            }
                        }
                    }
                }
            }
        }
        if (!ready) {
            item {
                FillSkeleton(cards = 5)
            }
        } else if (query.isBlank()) {
            if (jumpGroup != null) {
                val group = jumpGroup
                item {
                    Row(
                        modifier = Modifier.fillMaxWidth().clickable { jumpGroup = null }.padding(vertical = 10.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Text(
                            "← 全部配置",
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.primary,
                        )
                        Spacer(Modifier.weight(1f))
                        Text(
                            group ?: "",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
            }
            if (onlyChanged && changedTotal == 0) {
                item {
                    InfoCard {
                        Text(
                            "当前没有任何改动：所有配置项都还是官方默认值。",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
            }
            optionGroup(
                title = "通用配置",
                note = "所有后端通用。标「自动 / 开 / 关」的项，自动就是官方默认：不写这个键，由 MobileGL 按设备能力自行判断。改动后点「保存配置」写入。",
                keys = if (groupShown("通用配置")) visible(COMMON_KEYS) else emptyList(),
                text = text,
                parsed = parsed,
            ) { key, value -> text = setKey(text, key, value) }
            optionGroup(
                title = "管线",
                note = "前后端命令传递相关的进阶选项。",
                keys = if (groupShown("管线")) visible(PIPE_KEYS) else emptyList(),
                text = text,
                parsed = parsed,
            ) { key, value -> text = setKey(text, key, value) }
            optionGroup(
                title = "兼容性",
                note = "针对特定光影包或驱动的兼容处理。默认值通常可用；仅在出现具体问题时按需开启。",
                keys = if (groupShown("兼容性")) visible(COMPAT_KEYS) else emptyList(),
                text = text,
                parsed = parsed,
            ) { key, value -> text = setKey(text, key, value) }
            optionGroup(
                title = "诊断",
                note = "输出日志与内部校验，用于定位问题。日常开启会产生额外开销。",
                keys = if (groupShown("诊断")) visible(DIAG_KEYS) else emptyList(),
                text = text,
                parsed = parsed,
            ) { key, value -> text = setKey(text, key, value) }
            if (groupShown("DirectVulkan / Magma 专用") && visible(MAGMA_KEYS).isNotEmpty()) item {
                SectionLabel("DirectVulkan / Magma 专用", visible(MAGMA_KEYS).size)
                InfoCard {
                    Text(
                        "仅在渲染后端为 DirectVulkan 时生效。已按官方默认值配置，通常无需改动。",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Spacer(Modifier.height(8.dp))
                    OutlinedButton(
                        modifier = Modifier.fillMaxWidth(),
                        onClick = { showMagma = !showMagma },
                    ) { Text(if (showMagma || onlyChanged) "收起" else "展开 " + visible(MAGMA_KEYS).size + " 项") }
                    if (showMagma || onlyChanged) {
                        Spacer(Modifier.height(4.dp))
                        OptionRows(visible(MAGMA_KEYS), text, parsed) { key, value -> text = setKey(text, key, value) }
                    }
                }
            }
            if (groupShown("DirectGLES / Espryt 专用") && visible(ESPRYT_KEYS).isNotEmpty()) item {
                SectionLabel("DirectGLES / Espryt 专用", visible(ESPRYT_KEYS).size)
                InfoCard {
                    Text(
                        "仅在渲染后端为 DirectGLES 时生效。已按官方默认值配置，通常无需改动。",
                        style = MaterialTheme.typography.labelSmall,
