            }
            }
            item {
                SectionLabel("诊断")
                InfoCard {
            OptionToggle("管线统计", "MOBILEGL_PIPE_STATS", text, desc = "输出前后端之间每次调用的字节数、次数等计数，用来分析性能瓶颈在哪", default = "关", parsed = parsed) { text = setKey(text, "MOBILEGL_PIPE_STATS", onOff(it)) }
