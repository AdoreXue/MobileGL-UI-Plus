            color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
        )
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            listOf("自动", "开", "关").forEach { option ->
                FilterChip(
                    selected = option == value,
                    onClick = {
                        onChange(
                            when (option) {
                                "开" -> "1"
                                "关" -> "0"
                                else -> "auto"
                            },
                        )
                    },
                    label = { Text(option) },
                )
            }
        }
    }
